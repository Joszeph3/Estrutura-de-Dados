lista1 = [10, 20, 30]
lista2 = [5, 10, 15]

total1 = sum(lista1)
total2 = sum(lista2)

resultado = total1 + total2

print("Lista 1:", lista1)
print("Lista 2:", lista2)
print("--------------------------------------")
print("Soma da lista 1:", total1)
print("Soma da lista 2:", total2)
print("Soma das duas listas:", resultado)

# Criei duas listas contendo números, a função sum() soma todos os valores de cada lista
# depois armazenei o total de cada lista nas variáveis total1 e total2,
# no fim somei os dois resultados para encontrar o valor total das duas listas.